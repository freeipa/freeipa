#include <assert.h>
#include <string.h>

#include "ipa_pwd.h"

static const struct {
    char *password;
    uint8_t hash[16];
} cases[] = {
    { "", { 0x31, 0xd6, 0xcf, 0xe0, 0xd1, 0x6a, 0xe9, 0x31,
            0xb7, 0x3c, 0x59, 0xd7, 0xe0, 0xc0, 0x89, 0xc0 } },
    { "password", { 0x88, 0x46, 0xf7, 0xea, 0xee, 0x8f, 0xb1, 0x17,
                    0xad, 0x06, 0xbd, 0xd8, 0x30, 0xb7, 0x58, 0x6c } },
    { "Password", { 0xa4, 0xf4, 0x9c, 0x40, 0x65, 0x10, 0xbd, 0xca,
                    0xb6, 0x82, 0x4e, 0xe7, 0xc3, 0x0f, 0xd8, 0x52 } },
    { "t\xc3\xa9st", { 0x5d, 0x6b, 0xbd, 0xec, 0xcd, 0x62, 0xba, 0x9e,
                        0x61, 0xe0, 0xc6, 0xfb, 0x9a, 0x1a, 0x7f, 0x15 } },
};

int main(void)
{
    uint8_t hash[16];
    size_t i;

    for (i = 0; i < sizeof(cases) / sizeof(cases[0]); i++) {
        assert(encode_nt_key(cases[i].password, hash) == 0);
        assert(memcmp(hash, cases[i].hash, sizeof(hash)) == 0);
    }
    assert(encode_nt_key("\xff", hash) == -1);

    return 0;
}
